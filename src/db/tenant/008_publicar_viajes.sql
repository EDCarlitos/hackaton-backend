-- RF-05 a RF-11: publicar, clonar, plantillas "Salgo hoy", cancelar y avisos dentro de la app.

-- La plantilla guarda todo lo necesario para publicar sin volver a consultar Google (RF-07/09).
ALTER TABLE trayectos
  ADD COLUMN vehiculo_id  integer     NOT NULL,
  ADD COLUMN asientos     smallint    NOT NULL,
  ADD COLUMN distancia_km numeric(6,2),
  ADD COLUMN duracion_min integer,
  ADD COLUMN creado_en    timestamptz NOT NULL DEFAULT now(),
  ADD CONSTRAINT fk_trayectos_vehiculo_conductor FOREIGN KEY (vehiculo_id, conductor_id)
    REFERENCES vehiculos (id, usuario_id) ON DELETE RESTRICT,
  ADD CONSTRAINT chk_trayectos_asientos CHECK (asientos BETWEEN 1 AND 4),
  ADD CONSTRAINT chk_trayectos_ruta     CHECK (distancia_km >= 0 AND duracion_min >= 0);

ALTER TABLE viajes
  ADD COLUMN cancelado_en       timestamptz,
  ADD COLUMN motivo_cancelacion varchar(300),
  ADD CONSTRAINT chk_cancelado CHECK (estado <> 'cancelado' OR cancelado_en IS NOT NULL),
  ADD CONSTRAINT chk_viajes_ruta CHECK (distancia_km >= 0 AND duracion_min >= 0);

COMMENT ON COLUMN viajes.motivo_cancelacion IS 'Opcional; se incluye en el aviso a los pasajeros';

-- Avisos dentro de la app (RF-11: viaje cancelado). Se crean en la misma transacción que el evento.
CREATE TABLE notificaciones (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  tipo       varchar(40)   NOT NULL,
  titulo     varchar(120)  NOT NULL,
  mensaje    varchar(1000) NOT NULL,
  viaje_id   integer       REFERENCES viajes (id) ON DELETE CASCADE,
  leida_en   timestamptz,
  creada_en  timestamptz   NOT NULL DEFAULT now()
);

CREATE INDEX idx_notificaciones_usuario_creada_en ON notificaciones (usuario_id, creada_en DESC);

COMMENT ON COLUMN notificaciones.tipo IS 'Ver shared/constants/estados.js (TIPOS_NOTIFICACION)';
