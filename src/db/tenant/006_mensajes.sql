-- Chat del viaje (RF-23).

CREATE TABLE mensajes (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  viaje_id   integer      NOT NULL REFERENCES viajes (id) ON DELETE CASCADE,
  autor_id   integer      NOT NULL REFERENCES usuarios (id) ON DELETE RESTRICT,
  texto      varchar(500) NOT NULL CHECK (length(trim(texto)) > 0),
  enviado_en timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX idx_mensajes_viaje_enviado_en ON mensajes (viaje_id, enviado_en);

COMMENT ON COLUMN mensajes.autor_id IS 'Conductor o pasajero con reserva confirmada (se valida en Express)';
