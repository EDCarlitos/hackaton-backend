CREATE TABLE public.instituciones (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        varchar(150) NOT NULL,
  schema_nombre varchar(63)  NOT NULL UNIQUE,
  activo        boolean      NOT NULL DEFAULT true,
  creado_en     timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT chk_schema_nombre CHECK (schema_nombre ~ '^[a-z_][a-z0-9_]{0,62}$')
);

COMMENT ON COLUMN public.instituciones.schema_nombre IS
  'Schema del tenant, ej. ucaribe. Validar ^[a-z_][a-z0-9_]*$ antes de usarlo en SQL';

CREATE TABLE public.dominios_permitidos (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institucion_id integer     NOT NULL REFERENCES public.instituciones (id) ON DELETE RESTRICT,
  dominio        citext      NOT NULL UNIQUE,
  activo         boolean     NOT NULL DEFAULT true,
  creado_en      timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN public.dominios_permitidos.dominio IS
  'Ej. ucaribe.edu.mx; registrar también subdominios (alumnos.ucaribe.edu.mx)';

CREATE INDEX idx_dominios_permitidos_institucion_id
  ON public.dominios_permitidos (institucion_id);
