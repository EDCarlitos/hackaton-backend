CREATE TABLE viajes (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id         integer      NOT NULL REFERENCES usuarios (id) ON DELETE RESTRICT,
  vehiculo_id          integer      NOT NULL,
  trayecto_id          integer      REFERENCES trayectos (id) ON DELETE SET NULL,
  origen_lat           numeric(9,6) NOT NULL CHECK (origen_lat BETWEEN -90 AND 90),
  origen_lng           numeric(9,6) NOT NULL CHECK (origen_lng BETWEEN -180 AND 180),
  origen_texto         varchar(200),
  destino_lat          numeric(9,6) NOT NULL CHECK (destino_lat BETWEEN -90 AND 90),
  destino_lng          numeric(9,6) NOT NULL CHECK (destino_lng BETWEEN -180 AND 180),
  destino_texto        varchar(200),
  polilinea            text         NOT NULL,
  distancia_km         numeric(6,2),
  duracion_min         integer,
  salida_en            timestamptz  NOT NULL,
  asientos_ofrecidos   smallint     NOT NULL,
  asientos_disponibles smallint     NOT NULL,
  costo_referencia     numeric(8,2),
  estado               public.estado_viaje NOT NULL DEFAULT 'abierto',
  iniciado_en          timestamptz,
  reservas_cierran_en  timestamptz,
  finalizado_en        timestamptz,
  creado_en            timestamptz  NOT NULL DEFAULT now(),

  -- El vehículo del viaje tiene que ser del conductor.
  CONSTRAINT fk_viajes_vehiculo_conductor FOREIGN KEY (vehiculo_id, conductor_id)
    REFERENCES vehiculos (id, usuario_id) ON DELETE RESTRICT,

  CONSTRAINT chk_asientos_ofrecidos   CHECK (asientos_ofrecidos BETWEEN 1 AND 4),
  CONSTRAINT chk_asientos_disponibles CHECK (asientos_disponibles BETWEEN 0 AND asientos_ofrecidos),
  CONSTRAINT chk_costo                CHECK (costo_referencia IS NULL OR costo_referencia >= 0),
  CONSTRAINT chk_iniciado             CHECK (estado NOT IN ('en_curso', 'finalizado') OR iniciado_en IS NOT NULL),
  CONSTRAINT chk_finalizado           CHECK (estado <> 'finalizado' OR finalizado_en IS NOT NULL)
);

CREATE INDEX idx_viajes_estado_salida_en ON viajes (estado, salida_en);
CREATE INDEX idx_viajes_conductor_id     ON viajes (conductor_id);
CREATE INDEX idx_viajes_trayecto_id      ON viajes (trayecto_id);

COMMENT ON COLUMN viajes.origen_texto IS 'Aproximado, sin domicilio exacto';
COMMENT ON COLUMN viajes.polilinea IS 'overview_polyline de Google Maps; se consulta 1 vez';
COMMENT ON COLUMN viajes.asientos_disponibles IS
  'Actualizar junto con reservas en la misma transacción (SELECT ... FOR UPDATE sobre el viaje)';
COMMENT ON COLUMN viajes.costo_referencia IS 'No vinculante';
COMMENT ON COLUMN viajes.iniciado_en IS 'Cuando el conductor presiona "Iniciar viaje"';
COMMENT ON COLUMN viajes.reservas_cierran_en IS 'iniciado_en + 4 min';
