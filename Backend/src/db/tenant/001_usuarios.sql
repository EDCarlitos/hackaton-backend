-- Se aplica en CADA schema de institución (search_path = <schema>, public).

CREATE TABLE usuarios (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo               citext       NOT NULL UNIQUE,
  password_hash        varchar(255) NOT NULL,
  nombre_visible       varchar(100) NOT NULL,
  rol                  public.rol_usuario NOT NULL DEFAULT 'usuario',
  correo_verificado_en timestamptz,
  acepto_terminos_en   timestamptz,
  activo               boolean      NOT NULL DEFAULT true,
  creado_en            timestamptz  NOT NULL DEFAULT now()
);

COMMENT ON COLUMN usuarios.correo IS
  'Su dominio debe estar en dominios_permitidos de ESTA institución (se valida en Express al registrar)';
COMMENT ON COLUMN usuarios.password_hash IS 'bcrypt';
COMMENT ON COLUMN usuarios.correo_verificado_en IS
  'NULL = no puede iniciar sesión; prueba que el correo institucional es suyo';
COMMENT ON COLUMN usuarios.activo IS 'Suspender sin borrar historial';
