CREATE TABLE vehiculos (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id          integer      NOT NULL REFERENCES usuarios (id) ON DELETE RESTRICT,
  placa_o_descripcion varchar(100) NOT NULL,
  asientos            smallint     NOT NULL CHECK (asientos BETWEEN 1 AND 4),
  activo              boolean      NOT NULL DEFAULT true,

  -- Destino de la FK compuesta desde viajes: garantiza que el vehículo sea del conductor.
  CONSTRAINT ux_vehiculos_id_usuario UNIQUE (id, usuario_id)
);

CREATE INDEX idx_vehiculos_usuario_id ON vehiculos (usuario_id);

COMMENT ON COLUMN vehiculos.activo IS 'Desactivar en vez de borrar: viajes pasados lo referencian';
