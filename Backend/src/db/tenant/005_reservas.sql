CREATE TABLE reservas (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  viaje_id        integer      NOT NULL REFERENCES viajes (id) ON DELETE CASCADE,
  pasajero_id     integer      NOT NULL REFERENCES usuarios (id) ON DELETE RESTRICT,
  recogida_lat    numeric(9,6) NOT NULL CHECK (recogida_lat BETWEEN -90 AND 90),
  recogida_lng    numeric(9,6) NOT NULL CHECK (recogida_lng BETWEEN -180 AND 180),
  recogida_texto  varchar(200),
  bajada_lat      numeric(9,6) CHECK (bajada_lat BETWEEN -90 AND 90),
  bajada_lng      numeric(9,6) CHECK (bajada_lng BETWEEN -180 AND 180),
  distancia_pie_m integer      CHECK (distancia_pie_m >= 0),
  estado          public.estado_reserva NOT NULL DEFAULT 'solicitada',
  solicitada_en   timestamptz  NOT NULL DEFAULT now(),
  respondida_en   timestamptz,

  CONSTRAINT chk_bajada_completa CHECK ((bajada_lat IS NULL) = (bajada_lng IS NULL))
);

CREATE INDEX idx_reservas_viaje_estado    ON reservas (viaje_id, estado);
CREATE INDEX idx_reservas_pasajero_estado ON reservas (pasajero_id, estado);

-- Una sola reserva ACTIVA por pasajero y viaje; se puede volver a pedir tras cancelar o rechazar.
CREATE UNIQUE INDEX ux_reserva_activa ON reservas (viaje_id, pasajero_id)
  WHERE estado IN ('solicitada', 'confirmada');

COMMENT ON COLUMN reservas.pasajero_id IS 'Distinto de viajes.conductor_id (se valida en Express)';
